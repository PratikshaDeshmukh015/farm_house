/**
 * Parses image gallery array from raw farmhouse object
 */
export const parseRawImages = (farmhouse) => {
  if (!farmhouse) return [];
  let urls = [];

  if (Array.isArray(farmhouse.imageUrls) && farmhouse.imageUrls.length > 0) {
    urls = farmhouse.imageUrls;
  } else if (typeof farmhouse.imageUrls === 'string') {
    try {
      const parsed = JSON.parse(farmhouse.imageUrls);
      if (Array.isArray(parsed) && parsed.length) urls = parsed;
      else if (typeof parsed === 'string') urls = [parsed];
    } catch {
      if (farmhouse.imageUrls.includes(',')) {
        urls = farmhouse.imageUrls.split(',').map(s => s.trim()).filter(Boolean);
      } else {
        urls = [farmhouse.imageUrls];
      }
    }
  }

  if (farmhouse.imageUrl && !urls.includes(farmhouse.imageUrl)) {
    urls.unshift(farmhouse.imageUrl);
  }

  return urls.filter(u => typeof u === 'string' && u.trim().length > 0);
};

/**
 * Returns complete interactive photo gallery for a given farmhouse
 */
export const getFarmhouseGalleryPhotos = (farmhouse) => {
  if (!farmhouse) return [];

  const fhId = Number(farmhouse.id);
  const curated = FARMHOUSE_CURATED_GALLERIES[fhId] || [];
  const rawUrls = parseRawImages(farmhouse);

  const photoList = [];

  // 1. Add any custom uploaded images first
  rawUrls.forEach((url, idx) => {
    const alreadyExists = curated.some(c => c.image === url);
    if (!alreadyExists) {
      photoList.push({
        id: `custom-${fhId}-${idx}`,
        farmhouseId: fhId,
        farmhouseName: farmhouse.name,
        title: idx === 0 ? `${farmhouse.name} — Main Exterior` : `${farmhouse.name} — View ${idx + 1}`,
        category: idx % 2 === 0 ? 'Exterior' : 'Pools & Outdoors',
        location: farmhouse.location,
        image: url,
        aspect: idx % 3 === 0 ? 'tall' : 'medium'
      });
    }
  });

  // 2. Add curated high-res photos for this farmhouse
  if (curated.length > 0) {
    curated.forEach((photo) => {
      photoList.push({
        ...photo,
        farmhouseName: farmhouse.name || photo.farmhouseName,
        location: farmhouse.location || photo.location
      });
    });
  } else {
    // If no curated set (e.g. newly created farmhouse), provide high quality themed images
    const loc = (farmhouse.location || '').toLowerCase();
    let templateId = 1;
    if (loc.includes('goa') || loc.includes('beach')) templateId = 2;
    else if (loc.includes('pune') || loc.includes('latur') || loc.includes('mumbai') || loc.includes('lonavala')) templateId = 3;
    else if (loc.includes('uttarakhand') || loc.includes('river')) templateId = 4;
    else if (loc.includes('rajasthan') || loc.includes('jaipur')) templateId = 5;

    const templatePhotos = FARMHOUSE_CURATED_GALLERIES[templateId] || FARMHOUSE_CURATED_GALLERIES[1];
    templatePhotos.forEach((tp, idx) => {
      if (photoList.length < 7) {
        photoList.push({
          ...tp,
          id: `gen-${fhId}-${idx}`,
          farmhouseId: fhId,
          farmhouseName: farmhouse.name,
          location: farmhouse.location,
          title: `${farmhouse.name} · ${tp.category}`
        });
      }
    });
  }

  return photoList;
};
